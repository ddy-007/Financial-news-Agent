# 基线：2026-09-24 实测的最大值。**漂移告警用，不是断言值** ——
# 断的是「< DUP_THRESHOLD」，这个数只用来回答「有没有悄悄挪动」。
BASELINE_MAX = 0.8450

# ⚠️ **容差必须小于安全余量**（当前余量 0.8450→0.85 = 0.005）。
# 巡检 2026-09-24 指出：原取 0.01 时，「向上漂移但**还没越线**」这个区间
# **是空集** —— 任何 >0.01 的上升必然已经先触发 `❌` 硬断言，
# 于是「越线前预警」这一档永远不会单独出现，等于白写。
# 取 0.003 之后，向上漂移落在 (0.003, 0.005) 时会**单独**报「正在逼近」。
DRIFT_TOLERANCE = 0.003


def main() -> int:
    texts = [_doc_text(t, c) for t, c in PAIRS]
    vecs = np.asarray(embed_documents(texts), dtype=np.float32)
    vecs /= np.linalg.norm(vecs, axis=1, keepdims=True)
    sims = vecs @ vecs.T

    pairs = sorted(
        ((float(sims[i, j]), i, j)
         for i in range(len(texts)) for j in range(i + 1, len(texts))),
        reverse=True,
    )
    top = pairs[0]
    margin = DUP_THRESHOLD - top[0]

    print(f"\n样本 {len(texts)} 条 / {len(pairs)} 对，DUP_THRESHOLD = {DUP_THRESHOLD}")
    print("最像的 3 对：")
    for s, i, j in pairs[:3]:
        print(f"  {s:.4f}  {PAIRS[i][0][:24]}  ≈  {PAIRS[j][0][:24]}")
    print(f"\n最大非重复对 = {top[0]:.4f}｜距阈值余量 = {margin:.4f}")

    ok = True
    if top[0] >= DUP_THRESHOLD:
        ok = False
        print(f"\n❌ **失败**：{top[0]:.4f} ≥ {DUP_THRESHOLD} —— 这一对会被**直接合并、"
              f"不过 LLM**，而人是看得出它们是两条不同的事。")
        print("   → 最可能的原因：换了嵌入模型版本，或改了 `_doc_text` 的文本格式。")
        print("   → 处置：抬高 `DUP_THRESHOLD`（且必须与 §13.3 的灰区成本一起看），"
              "或先加回旧模型复现。")
    else:
        print(f"✅ 通过：全部 {len(pairs)} 对都在阈值之下。")

    drift = top[0] - BASELINE_MAX
    if abs(drift) > DRIFT_TOLERANCE:
        # 分清方向：向上是「余量变小、更危险」，向下是「更安全但分布挪了」。
        # 两者都要说 —— 但语气不该一样，否则看的人分不出该不该紧张。
        direction = ("**向上（余量变小，正在逼近阈值）**" if drift > 0
                     else "向下（余量变大，更安全）")
        print(f"\n⚠️ 漂移告警：最大对相对基线（{BASELINE_MAX:.4f}）{direction}，"
              f"变了 {drift:+.4f}（容差 ±{DRIFT_TOLERANCE}）。"
              f"\n   请确认是不是有意为之，并把基线更新到本脚本的 `BASELINE_MAX`。")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
